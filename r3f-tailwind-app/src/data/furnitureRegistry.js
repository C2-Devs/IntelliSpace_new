/**
 * Lookup a furniture definition by its registry ID.
 */
export function getFurnitureById(id) {
  return REGISTRY.find((item) => item.id === id) || null;
}

/**
 * Get all furniture items for a given category.
 */
export function getFurnitureByCategory(category) {
  if (category === 'all') return REGISTRY;
  return REGISTRY.filter((item) => item.category === category);
}

/**
 * Search furniture by name (case-insensitive).
 */
export function searchFurniture(query) {
  const q = query.toLowerCase().trim();
  if (!q) return REGISTRY;
  return REGISTRY.filter((item) => item.name.toLowerCase().includes(q));
}

export function normalizeCatalogItem(item) {
  const normalization = item.normalization;
  const measuredDimensions = normalization?.measuredDimensions;
  return {
    ...item,
    catalogItemId: item.catalogItemId ?? item.catalog_item_id ?? item.id,
    modelPath: item.modelPath ?? item.model_path ?? null,
    defaultScale: item.defaultScale ?? [1, 1, 1],
    defaultRotation: item.defaultRotation ?? [0, 0, 0],
    snapHeight: Number.isFinite(item.snapHeight) ? item.snapHeight : 0,
    normalization,
    dimensions: {
      width: Number(item.dimensions?.width ?? item.width ?? measuredDimensions?.[0] ?? 1),
      height: Number(item.dimensions?.height ?? item.height ?? measuredDimensions?.[1] ?? 1),
      depth: Number(item.dimensions?.depth ?? item.depth ?? measuredDimensions?.[2] ?? 1),
    },
  };
}

export const NORMALIZED_REGISTRY = REGISTRY.map(normalizeCatalogItem);

export default NORMALIZED_REGISTRY;
